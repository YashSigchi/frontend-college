// Helper function to get unique locations
export const getUniqueLocations = (): string[] => {
  const locations = colleges.map((c) => `${c.location.city}, ${c.location.state}`);
  return Array.from(new Set(locations)).sort();
};

// Helper function to get unique course types
export const getCourseTypes = (): string[] => {
  return ['Undergraduate', 'Postgraduate', 'Diploma', 'PhD'];
};

// Helper function to get min/max fees for range
export const getFeesRange = (): [number, number] => {
  const allFees = colleges.flatMap((c) => [c.fees.min, c.fees.max]);
  return [Math.min.apply(null, allFees), Math.max.apply(null, allFees)];
};
